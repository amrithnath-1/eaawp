"""
Tool hub: the persistent registry of dynamically discovered (MCP) and generated internal tools, their versions, role
grants, every execution, MCP discovery snapshots and the tool audit trail.

Tenant isolation: every table carries tenant_id and every query filters by it.
No secrets are stored here: MCP credentials stay encrypted on the Integration row; generated tools never receive
credentials; execution records keep short sanitised summaries only.
"""
from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Index, Integer, String, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.models import Base


def _uuid() -> str:
    return str(uuid.uuid4())


class ToolRecord(Base):
    """One tool known to a company: discovered on an MCP server, or generated by the Tool Builder."""

    __tablename__ = "toolhub_tools"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    source: Mapped[str] = mapped_column(String(16), nullable=False)                 # "mcp" | "generated"
    integration_id: Mapped[str | None] = mapped_column(String(36), nullable=True)   # MCP server connection
    key: Mapped[str] = mapped_column(String(128), nullable=False)                   # MCP tool name / generated slug
    name: Mapped[str] = mapped_column(String(160), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False, default="")
    input_schema_json: Mapped[str] = mapped_column(Text, nullable=False, default="{}")
    output_schema_json: Mapped[str] = mapped_column(Text, nullable=False, default="{}")
    risk_class: Mapped[str] = mapped_column(String(32), nullable=False, default="read_only")
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="active")   # active|removed|deactivated
    current_version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    schema_hash: Mapped[str] = mapped_column(String(64), nullable=False, default="")
    created_by: Mapped[str] = mapped_column(String(128), nullable=False, default="system")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    __table_args__ = (
        UniqueConstraint("tenant_id", "source", "integration_id", "key", name="uq_toolhub_tool"),
        Index("ix_toolhub_tools_tenant_source", "tenant_id", "source"),
    )


class ToolVersion(Base):
    """One version of a generated tool: its code, schemas, tests and validation report."""

    __tablename__ = "toolhub_tool_versions"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    tool_id: Mapped[str] = mapped_column(String(36), ForeignKey("toolhub_tools.id", ondelete="CASCADE"), nullable=False)
    version: Mapped[int] = mapped_column(Integer, nullable=False)
    purpose: Mapped[str] = mapped_column(Text, nullable=False, default="")
    code: Mapped[str] = mapped_column(Text, nullable=False, default="")
    input_schema_json: Mapped[str] = mapped_column(Text, nullable=False, default="{}")
    output_schema_json: Mapped[str] = mapped_column(Text, nullable=False, default="{}")
    tests_json: Mapped[str] = mapped_column(Text, nullable=False, default="[]")
    dependencies_json: Mapped[str] = mapped_column(Text, nullable=False, default="[]")
    validation_json: Mapped[str] = mapped_column(Text, nullable=False, default="{}")
    status: Mapped[str] = mapped_column(String(16), nullable=False)   # validated|rejected|active|superseded|rolled_back
    created_by: Mapped[str] = mapped_column(String(128), nullable=False, default="system")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        UniqueConstraint("tool_id", "version", name="uq_toolhub_tool_version"),
        Index("ix_toolhub_versions_tenant", "tenant_id", "tool_id"),
    )


class ToolGrant(Base):
    """A generated tool granted to one AI employee role (least privilege: nothing is granted by default)."""

    __tablename__ = "toolhub_tool_grants"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    tool_id: Mapped[str] = mapped_column(String(36), ForeignKey("toolhub_tools.id", ondelete="CASCADE"), nullable=False)
    role_key: Mapped[str] = mapped_column(String(128), nullable=False)
    granted_by: Mapped[str] = mapped_column(String(128), nullable=False, default="system")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        UniqueConstraint("tool_id", "role_key", name="uq_toolhub_grant"),
        Index("ix_toolhub_grants_tenant_role", "tenant_id", "role_key"),
    )


class ToolExecution(Base):
    """One execution of any tool by an AI employee (built-in, integration, MCP or generated)."""

    __tablename__ = "toolhub_executions"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    tool_key: Mapped[str] = mapped_column(String(255), nullable=False)
    tool_label: Mapped[str] = mapped_column(String(200), nullable=False, default="")
    tool_source: Mapped[str] = mapped_column(String(16), nullable=False, default="builtin")
    role_key: Mapped[str] = mapped_column(String(128), nullable=False)
    plan_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    status: Mapped[str] = mapped_column(String(16), nullable=False)        # success | failed | blocked
    error_category: Mapped[str | None] = mapped_column(String(32), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)
    duration_ms: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    retries: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    recovery: Mapped[str | None] = mapped_column(Text, nullable=True)       # what was done to recover, if anything
    input_summary: Mapped[str] = mapped_column(Text, nullable=False, default="")
    output_summary: Mapped[str] = mapped_column(Text, nullable=False, default="")
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        Index("ix_toolhub_exec_tenant_tool", "tenant_id", "tool_key", "started_at"),
        Index("ix_toolhub_exec_tenant_time", "tenant_id", "started_at"),
    )


class McpDiscoverySnapshot(Base):
    """The result of one discovery of an MCP server: what was added, removed or changed since the previous one."""

    __tablename__ = "toolhub_mcp_snapshots"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    integration_id: Mapped[str] = mapped_column(String(36), nullable=False)
    tool_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    schema_hash: Mapped[str] = mapped_column(String(64), nullable=False, default="")
    added_json: Mapped[str] = mapped_column(Text, nullable=False, default="[]")
    removed_json: Mapped[str] = mapped_column(Text, nullable=False, default="[]")
    changed_json: Mapped[str] = mapped_column(Text, nullable=False, default="[]")
    duration_ms: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (Index("ix_toolhub_snap_tenant_integration", "tenant_id", "integration_id", "created_at"),)


class ToolEvent(Base):
    """Tool audit trail: discovery changes, generation, validation, registration, grants, deactivation, rollback,
    missing-capability requests."""

    __tablename__ = "toolhub_events"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    tool_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    kind: Mapped[str] = mapped_column(String(32), nullable=False)
    actor: Mapped[str] = mapped_column(String(128), nullable=False, default="system")
    detail: Mapped[str] = mapped_column(Text, nullable=False, default="")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (Index("ix_toolhub_events_tenant_time", "tenant_id", "created_at"),)


class McpTask(Base):
    """A long-running operation started on an MCP server (a job), followed until it ends.

    state: CREATED → QUEUED/RUNNING → COMPLETED | FAILED | CANCELLED | TIMED_OUT | EXPIRED. The remote id is the one
    the server's own status mechanism takes (found from its schemas), never guessed. Terminal tasks are never polled.
    """

    __tablename__ = "toolhub_mcp_tasks"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    tenant_id: Mapped[str] = mapped_column(String(36), ForeignKey("companies.id", ondelete="CASCADE"), nullable=False)
    integration_id: Mapped[str] = mapped_column(String(36), nullable=False)
    role_key: Mapped[str] = mapped_column(String(128), nullable=False)
    plan_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    start_tool: Mapped[str] = mapped_column(String(128), nullable=False)
    args_hash: Mapped[str] = mapped_column(String(64), nullable=False, default="")
    args_summary: Mapped[str] = mapped_column(Text, nullable=False, default="")
    mechanism: Mapped[str] = mapped_column(String(16), nullable=False, default="tool")   # tool | mcp_tasks
    status_tool: Mapped[str | None] = mapped_column(String(128), nullable=True)
    status_param: Mapped[str | None] = mapped_column(String(64), nullable=True)
    cancel_tool: Mapped[str | None] = mapped_column(String(128), nullable=True)
    remote_id: Mapped[str] = mapped_column(String(255), nullable=False)
    remote_id_field: Mapped[str] = mapped_column(String(64), nullable=False, default="id")
    state: Mapped[str] = mapped_column(String(16), nullable=False, default="CREATED")
    remote_status: Mapped[str | None] = mapped_column(String(64), nullable=True)
    poll_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    poll_failures: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    last_poll_error: Mapped[str | None] = mapped_column(Text, nullable=True)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    result_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    next_poll_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    deadline_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    __table_args__ = (
        Index("ix_toolhub_tasks_tenant_time", "tenant_id", "created_at"),
        Index("ix_toolhub_tasks_state_poll", "state", "next_poll_at"),
        Index("ix_toolhub_tasks_dedupe", "tenant_id", "integration_id", "start_tool", "args_hash"),
    )
